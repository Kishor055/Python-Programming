# 04_data_types.py

# Integer
age = 20

# Float
price = 99.50

# String
name = "Rahul"

# Boolean
is_student = True

# List
fruits = ["Apple", "Banana", "Mango"]

# Tuple
coordinates = (10, 20)

# Set
numbers = {1, 2, 3, 4}

# Dictionary
student = {
    "name": "Rahul",
    "age": 20
}

print("Integer:", age)
print("Float:", price)
print("String:", name)
print("Boolean:", is_student)
print("List:", fruits)
print("Tuple:", coordinates)
print("Set:", numbers)
print("Dictionary:", student)
