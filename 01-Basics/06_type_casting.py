# 06_type_casting.py

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
x = 10.5
y = int(x)
print("Float to Integer:", y)

# Integer to String
num = 100
text = str(num)
print("Integer to String:", text)

# String to Integer
value = "25"
number = int(value)
print("String to Integer:", number)

# String to Float
price = "99.50"
amount = float(price)
print("String to Float:", amount)

# Integer to Boolean
n = 1
print("Integer to Boolean:", bool(n))

# Boolean to Integer
flag = True
print("Boolean to Integer:", int(flag))

"""
Key points
Type casting means converting one data type into another.
int() → converts to integer.
float() → converts to floating-point number.
str() → converts to string.
bool() → converts to Boolean (True/False).
"""
