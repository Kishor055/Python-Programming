# ============================================================
# Python Operators
# File: 01_arithmetic_operators.py
# Description: Demonstrates Python arithmetic operators.
# ============================================================


# ------------------------------------------------------------
# Variables
# ------------------------------------------------------------

a = 15
b = 4


# ------------------------------------------------------------
# 1. Addition (+)
# ------------------------------------------------------------

result = a + b

print("Addition:", result)


# ------------------------------------------------------------
# 2. Subtraction (-)
# ------------------------------------------------------------

result = a - b

print("Subtraction:", result)


# ------------------------------------------------------------
# 3. Multiplication (*)
# ------------------------------------------------------------

result = a * b

print("Multiplication:", result)


# ------------------------------------------------------------
# 4. Division (/)
# ------------------------------------------------------------

result = a / b

print("Division:", result)


# ------------------------------------------------------------
# 5. Floor Division (//)
# ------------------------------------------------------------

result = a // b

print("Floor Division:", result)


# ------------------------------------------------------------
# 6. Modulus (%)
# ------------------------------------------------------------

result = a % b

print("Modulus:", result)


# ------------------------------------------------------------
# 7. Exponentiation (**)
# ------------------------------------------------------------

result = a ** b

print("Exponentiation:", result)
