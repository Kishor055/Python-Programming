# ============================================================
# Python Operators
# File: 02_assignment_operators.py
# Description: Demonstrates Python assignment operators.
# ============================================================


# ------------------------------------------------------------
# 1. Assignment Operator (=)
# ------------------------------------------------------------

x = 10

print("Assignment:", x)


# ------------------------------------------------------------
# 2. Addition Assignment (+=)
# ------------------------------------------------------------

x = 10
x += 5

print("Addition Assignment:", x)


# ------------------------------------------------------------
# 3. Subtraction Assignment (-=)
# ------------------------------------------------------------

x = 10
x -= 3

print("Subtraction Assignment:", x)


# ------------------------------------------------------------
# 4. Multiplication Assignment (*=)
# ------------------------------------------------------------

x = 10
x *= 2

print("Multiplication Assignment:", x)


# ------------------------------------------------------------
# 5. Division Assignment (/=)
# ------------------------------------------------------------

x = 10
x /= 2

print("Division Assignment:", x)


# ------------------------------------------------------------
# 6. Floor Division Assignment (//=)
# ------------------------------------------------------------

x = 10
x //= 3

print("Floor Division Assignment:", x)


# ------------------------------------------------------------
# 7. Modulus Assignment (%=)
# ------------------------------------------------------------

x = 10
x %= 3

print("Modulus Assignment:", x)


# ------------------------------------------------------------
# 8. Exponentiation Assignment (**=)
# ------------------------------------------------------------

x = 2
x **= 3

print("Exponentiation Assignment:", x)


# ------------------------------------------------------------
# 9. Bitwise AND Assignment (&=)
# ------------------------------------------------------------

x = 10
x &= 4

print("Bitwise AND Assignment:", x)


# ------------------------------------------------------------
# 10. Bitwise OR Assignment (|=)
# ------------------------------------------------------------

x = 10
x |= 4

print("Bitwise OR Assignment:", x)


# ------------------------------------------------------------
# 11. Bitwise XOR Assignment (^=)
# ------------------------------------------------------------

x = 10
x ^= 4

print("Bitwise XOR Assignment:", x)


# ------------------------------------------------------------
# 12. Left Shift Assignment (<<=)
# ------------------------------------------------------------

x = 10
x <<= 2

print("Left Shift Assignment:", x)


# ------------------------------------------------------------
# 13. Right Shift Assignment (>>=)
# ------------------------------------------------------------

x = 10
x >>= 2

print("Right Shift Assignment:", x)

