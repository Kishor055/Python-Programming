# Description: Demonstrates Python comparison operators.
# ============================================================


# ------------------------------------------------------------
# Variables
# ------------------------------------------------------------

a = 10
b = 20


# ------------------------------------------------------------
# 1. Equal To (==)
# ------------------------------------------------------------

result = a == b

print("Equal To:", result)


# ------------------------------------------------------------
# 2. Not Equal To (!=)
# ------------------------------------------------------------

result = a != b

print("Not Equal To:", result)


# ------------------------------------------------------------
# 3. Greater Than (>)
# ------------------------------------------------------------

result = a > b

print("Greater Than:", result)


# ------------------------------------------------------------
# 4. Less Than (<)
# ------------------------------------------------------------

result = a < b

print("Less Than:", result)


# ------------------------------------------------------------
# 5. Greater Than or Equal To (>=)
# ------------------------------------------------------------

result = a >= b

print("Greater Than or Equal To:", result)


# ------------------------------------------------------------
# 6. Less Than or Equal To (<=)
# ------------------------------------------------------------

result = a <= b

print("Less Than or Equal To:", result)

