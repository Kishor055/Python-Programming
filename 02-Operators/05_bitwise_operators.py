# ============================================================
# Python Operators
# File: 05_bitwise_operators.py
# Description: Demonstrates Python bitwise operators.
# ============================================================


# ------------------------------------------------------------
# Variables
# ------------------------------------------------------------

a = 10    # Binary: 1010
b = 4     # Binary: 0100


# ------------------------------------------------------------
# 1. Bitwise AND (&)
# ------------------------------------------------------------

result = a & b

print("Bitwise AND:", result)


# ------------------------------------------------------------
# 2. Bitwise OR (|)
# ------------------------------------------------------------

result = a | b

print("Bitwise OR:", result)


# ------------------------------------------------------------
# 3. Bitwise XOR (^)
# ------------------------------------------------------------

result = a ^ b

print("Bitwise XOR:", result)


# ------------------------------------------------------------
# 4. Bitwise NOT (~)
# ------------------------------------------------------------

result = ~a

print("Bitwise NOT:", result)


# ------------------------------------------------------------
# 5. Left Shift (<<)
# ------------------------------------------------------------

result = a << 2

print("Left Shift:", result)


# ------------------------------------------------------------
# 6. Right Shift (>>)
# ------------------------------------------------------------

result = a >> 2

print("Right Shift:", result)
