# ============================================================
# Python Operators
# File: 07_identity_operators.py
# Description: Demonstrates Python identity operators.
# ============================================================


# ------------------------------------------------------------
# 1. Identity Operator (is)
# ------------------------------------------------------------

a = [1, 2, 3]
b = a

result = a is b

print("a is b:", result)


# ------------------------------------------------------------
# 2. Identity Operator (is not)
# ------------------------------------------------------------

a = [1, 2, 3]
b = [1, 2, 3]

result = a is not b

print("a is not b:", result)


# ------------------------------------------------------------
# 3. Same Object vs Different Object
# ------------------------------------------------------------

a = [10, 20, 30]

b = a
c = [10, 20, 30]

print("a is b:", a is b)
print("a is c:", a is c)


# ------------------------------------------------------------
# 4. Identity vs Equality
# ------------------------------------------------------------

x = [1, 2, 3]
y = [1, 2, 3]

print("x == y:", x == y)
print("x is y:", x is y)


# ------------------------------------------------------------
# 5. Checking for None
# ------------------------------------------------------------

value = None

if value is None:
    print("Value is None.")


# ------------------------------------------------------------
# 6. Practical Example
# ------------------------------------------------------------

user = None

if user is None:
    print("No user is currently logged in.")
else:
    print("User is logged in.")
