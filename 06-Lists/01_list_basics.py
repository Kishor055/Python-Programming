"""
01_list_basics.py
=================

Python List Basics

A list is an ordered, mutable collection of elements.
Lists are created using square brackets [].

Key properties:
    - Ordered
    - Mutable
    - Indexed
    - Sliceable
    - Iterable
    - Allows duplicate values
    - Supports multiple data types
    - Can contain nested lists
"""

